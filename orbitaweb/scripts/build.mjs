import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceFiles = [
  'src/constants.js',
  'src/core/music.js',
  'src/core/interaction.js',
  'src/core/project.js',
  'src/core/transport.js',
  'src/audio/synth-voices.js',
  'src/audio/audio-engine.js',
  'src/storage/project-store.js',
  'src/ui/gestures.js',
  'src/ui/orbita-view.js',
  'src/ui/app-controller.js',
  'src/main.js',
];

function removeModuleSyntax(source) {
  return source
    .replace(/^import\s+[\s\S]*?\s+from\s+['"][^'"]+['"];\s*/gm, '')
    .replace(/^export\s+/gm, '');
}

const modules = sourceFiles.map((relativePath) => {
  const source = readFileSync(resolve(projectRoot, relativePath), 'utf8');
  return `\n  // ${relativePath}\n${removeModuleSyntax(source)}`;
});

const bundle = `/* Generated by scripts/build.mjs. Do not edit directly. */
(function () {
  'use strict';
${modules.join('\n')}
})();
`;

const outputPath = resolve(projectRoot, 'dist/app.js');
mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, bundle);
console.log(`Built ${outputPath}`);
